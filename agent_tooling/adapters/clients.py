"""Client adapters for OpenCode V2, Codex, Claude Code (.mcp.json), and Antigravity (.agents/mcp_config.json)."""
from __future__ import annotations

import json
from typing import Any


def render_opencode_v2(servers: dict[str, dict[str, Any]]) -> str:
    """Render OpenCode V2 opencode.jsonc payload."""
    oc_servers: dict[str, Any] = {}
    for name, cfg in servers.items():
        if "opencode" not in cfg.get("supported_clients", []):
            continue
        transport = cfg.get("transport", "stdio")
        if transport == "stdio":
            cmd = [cfg["executable"]] + list(cfg.get("args", []))
            oc_servers[name] = {"type": "local", "command": cmd, "disabled": False}
        else:
            oc_servers[name] = {"type": "remote", "disabled": False}
    payload = {
        "$schema": "https://opencode.ai/config.json",
        "mcp": {"servers": oc_servers},
    }
    return json.dumps(payload, indent=2)


def render_codex_toml(servers: dict[str, dict[str, Any]], profiles: list[str]) -> str:
    """Render Codex .codex/config.toml payload."""
    lines = [f"# Generated by agent_tooling v3 for profiles: {', '.join(profiles)}"]
    for name, cfg in servers.items():
        if "codex" not in cfg.get("supported_clients", []):
            continue
        if cfg.get("transport", "stdio") != "stdio":
            continue
        exe = str(cfg["executable"]).replace("\\", "/")
        args = ", ".join(f'"{str(a).replace(chr(92), "/")}"' for a in cfg.get("args", []))
        lines.extend([
            "",
            f"[mcp_servers.{name}]",
            f'command = "{exe}"',
            f"args = [{args}]",
            "enabled = true",
        ])
    return "\n".join(lines) + "\n"


def render_claude_mcp_json(servers: dict[str, dict[str, Any]]) -> str:
    """Render Claude Code .mcp.json payload (stdio only, no secrets)."""
    mcp_servers: dict[str, Any] = {}
    for name, cfg in servers.items():
        if cfg.get("transport", "stdio") != "stdio":
            continue
        mcp_servers[name] = {
            "command": cfg["executable"],
            "args": list(cfg.get("args", [])),
        }
    return json.dumps({"mcpServers": mcp_servers}, indent=2)


