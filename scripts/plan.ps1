<#
.SYNOPSIS
  Plans per-repo opencode.jsonc, .codex/config.toml, and repo-level skills from profiles without modifying files.
#>
param(
  [Parameter(Mandatory = $true)]
  [string]$RepoPath,
  [Parameter(Mandatory = $true)]
  [string[]]$Profiles,
  [string]$ToolingRoot = "$env:USERPROFILE\.agents\tooling"
)

$ErrorActionPreference = 'Stop'

function Get-ProfileItems {
  param([string]$ProfileName, [string]$ProfilesDir, [string]$Section)
  $file = Join-Path $ProfilesDir "$ProfileName.yaml"
  if (-not (Test-Path $file)) { throw "Profile not found: $file" }
  $items = @()
  $inList = $false
  foreach ($line in (Get-Content $file)) {
    if ($line -match "^${Section}:\s*\[\]") { return @() }
    if ($line -match "^${Section}:\s*$") { $inList = $true; continue }
    if ($inList -and $line -match '^\s*-\s*(\S+)') {
      $items += $Matches[1].Trim()
    } elseif ($inList -and $line -match '^\S') {
      $inList = $false
    }
  }
  return $items
}

function Parse-Registry {
  param([string]$RegistryPath)
  $servers = @{}
  $current = $null
  foreach ($line in (Get-Content $RegistryPath)) {
    if ($line -match '^  ([a-zA-Z0-9_-]+):\s*$') {
      $current = $Matches[1]
      $servers[$current] = @{ transport = 'stdio'; executable = ''; args = @(); supported_clients = @() }
    } elseif ($current -and $line -match '^\s{4}transport:\s*(\S+)') {
      $servers[$current].transport = $Matches[1].Trim()
    } elseif ($current -and $line -match '^\s{4}executable:\s*"([^"]*)"') {
      $servers[$current].executable = $Matches[1]
    } elseif ($current -and $line -match '^\s{4}args:\s*\[(.*)\]') {
      $raw = $Matches[1].Trim()
      if ($raw) {
        $servers[$current].args = @($raw -split ',\s*' | ForEach-Object { $_.Trim().Trim('"') })
      }
    } elseif ($current -and $line -match '^\s{4}supported_clients:\s*\[(.*)\]') {
      $raw = $Matches[1].Trim()
      if ($raw) {
        $servers[$current].supported_clients = @($raw -split ',\s*' | ForEach-Object { $_.Trim() })
      }
    }
  }
  return $servers
}

$registryPath = Join-Path $ToolingRoot "registry.yaml"
if (-not (Test-Path $registryPath)) {
  $registryPath = Join-Path $ToolingRoot "registry.initial.yaml"
}
$profilesDir = Join-Path $ToolingRoot "profiles"
$registry = Parse-Registry -RegistryPath $registryPath

$expandedProfiles = @($Profiles | ForEach-Object { $_ -split ',' } | ForEach-Object { $_.Trim() } | Where-Object { $_ })

$selectedServers = @()
$selectedSkills = @()
foreach ($p in $expandedProfiles) {
  $selectedServers += Get-ProfileItems -ProfileName $p -ProfilesDir $profilesDir -Section "mcp_servers"
  $selectedSkills += Get-ProfileItems -ProfileName $p -ProfilesDir $profilesDir -Section "skills"
}
$selectedServers = $selectedServers | Select-Object -Unique
$selectedSkills = $selectedSkills | Select-Object -Unique

$ocServers = @{}
$codexTomlLines = @("# Generated by plan.ps1 for profiles: $($Profiles -join ', ')")

foreach ($s in $selectedServers) {
  if (-not $registry.ContainsKey($s)) {
    Write-Warning "Server '$s' not found in registry."
    continue
  }
  $def = $registry[$s]
  if ($def.supported_clients -contains 'opencode') {
    if ($def.transport -eq 'stdio') {
      $cmd = @($def.executable) + $def.args
      $ocServers[$s] = @{ type = 'local'; command = $cmd; disabled = $false }
    } else {
      $ocServers[$s] = @{ type = 'remote'; disabled = $false }
    }
  }
  if ($def.supported_clients -contains 'codex' -and $def.transport -eq 'stdio') {
    $argsToml = ($def.args | ForEach-Object { '"' + ($_ -replace '\\', '/') + '"' }) -join ', '
    $codexTomlLines += ""
    $codexTomlLines += "[mcp_servers.$s]"
    $codexTomlLines += "command = `"$($def.executable -replace '\\', '/')`""
    $codexTomlLines += "args = [$argsToml]"
    $codexTomlLines += "enabled = true"
  }
}

$ocObj = [ordered]@{
  '$schema' = 'https://opencode.ai/config.json'
  mcp = @{ servers = $ocServers }
}

[PSCustomObject]@{
  RepoPath = $RepoPath
  Profiles = $Profiles
  SelectedServers = $selectedServers
  SelectedSkills = $selectedSkills
  OpenCodeJsonc = ($ocObj | ConvertTo-Json -Depth 6)
  CodexToml = ($codexTomlLines -join "`r`n")
}
